// Kotlin output for Android (Compose) apps, gaulatti/bleecker#562. Dependency-free on purpose: colours are
// ARGB longs, lengths are Float dp, durations are Int ms, so an app wraps them in its own Compose types.
function argb(value) {
  const hex = /^#([0-9a-f]{6})$/i.exec(value);
  if (hex) return `0xFF${hex[1].toUpperCase()}L`;
  const rgba = /^rgba\(\s*(\d+),\s*(\d+),\s*(\d+),\s*([\d.]+)\s*\)$/.exec(value);
  if (!rgba) throw new Error(`Unsupported colour for Kotlin: ${value}`);
  const [r, g, b] = rgba.slice(1, 4).map(Number);
  const a = Math.round(Number(rgba[4]) * 255);
  return `0x${[a, r, g, b].map((part) => part.toString(16).toUpperCase().padStart(2, '0')).join('')}L`;
}

function kotlinObject(name, entries, doc) {
  const lines = entries.map(([, line]) => `    ${line}`);
  return `${doc ? `/** ${doc} */\n` : ''}object ${name} {\n${lines.join('\n')}\n}\n`;
}

function floatLiteral(value) {
  const text = String(value);
  return /[.e]/.test(text) ? `${text}f` : `${text}.0f`;
}

async function generateKotlin() {
  const tokens = await loadTokens();
  const objects = [
    kotlinObject('BleeckerFontFamilies', Object.entries(tokens.fontFamilies).map(([k, v]) => [k, `const val ${k} = "${v}"`])),
    kotlinObject('BleeckerFontWeights', Object.entries(tokens.fontWeights).map(([k, v]) => [k, `const val ${k} = ${v}`])),
    kotlinObject('BleeckerSpacing', Object.entries(tokens.spacing).map(([k, v]) => [k, `const val ${k} = ${floatLiteral(v)}`]), 'Density-independent pixels (dp).'),
    kotlinObject('BleeckerRadii', Object.entries(tokens.radii).map(([k, v]) => [k, `const val ${k} = ${floatLiteral(v)}`]), 'Density-independent pixels (dp); pill is a full radius.'),
    kotlinObject('BleeckerDurations', Object.entries(tokens.durations).map(([k, v]) => [k, `const val ${k} = ${v}`]), 'Milliseconds.'),
    kotlinObject('BleeckerLetterSpacing', Object.entries(tokens.letterSpacing).map(([k, v]) => [k, `const val ${k} = ${floatLiteral(v)}`]), 'In em.'),
    kotlinObject('BleeckerEasing', Object.entries(tokens.easing).map(([k, v]) => [k, `val ${k} = floatArrayOf(${v.map(floatLiteral).join(', ')})`]), 'Cubic Bezier control points x1, y1, x2, y2.'),
    kotlinObject('BleeckerLightColors', Object.entries(tokens.lightColors).map(([k, v]) => [k, `const val ${k} = ${argb(v)}`]), 'ARGB.'),
    kotlinObject('BleeckerDarkColors', Object.entries(tokens.darkColors).map(([k, v]) => [k, `const val ${k} = ${argb(v)}`]), 'ARGB.')
  ];
  return `// Generated by scripts/generate-token-css.mjs from src/tokens/source.ts. Do not edit.
package com.gaulatti.bleecker.tokens

${objects.join('\n')}`;
}

const expected = await generate();
const expectedKotlin = await generateKotlin();
if (process.argv.includes('--check')) {
  for (const [file, content] of [[outputPath, expected], [kotlinOutputPath, expectedKotlin]]) {
    const current = await fs.readFile(file, 'utf8').catch(() => '');
    if (current !== content) {
      console.error(`${path.relative(root, file)} is stale. Run npm run build:tokens.`);
      process.exitCode = 1;
    }
  }
} else {
  await fs.writeFile(outputPath, expected);
  await fs.mkdir(path.dirname(kotlinOutputPath), { recursive: true });
  await fs.writeFile(kotlinOutputPath, expectedKotlin);
  const globalCss = await fs.readFile(globalCssPath, 'utf8');
  const normalizedGlobalCss = globalCss
    .replace(/\/\* bleecker-generated-theme:start \*\/[\s\S]*?\/\* bleecker-generated-theme:end \*\//, '/* Design tokens are generated in tokens.generated.css. */')
    .replace(/\s*\/\* bleecker-generated-light:start \*\/[\s\S]*?\/\* bleecker-generated-light:end \*\//, '')
    .replace(/\s*\/\* bleecker-generated-dark:start \*\/[\s\S]*?\/\* bleecker-generated-dark:end \*\//, '');
  if (normalizedGlobalCss !== globalCss) {
    await fs.writeFile(globalCssPath, normalizedGlobalCss);
  }
  console.log(`[generate-token-css] Wrote ${path.relative(root, outputPath)} and ${path.relative(root, kotlinOutputPath)}.`);
}
