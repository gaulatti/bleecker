const expected = await generate();
if (process.argv.includes('--check')) {
  const current = await fs.readFile(outputPath, 'utf8').catch(() => '');
  if (current !== expected) {
    console.error(`${path.relative(root, outputPath)} is stale. Run npm run build:tokens.`);
    process.exitCode = 1;
  }
} else {
  await fs.writeFile(outputPath, expected);
  const globalCss = await fs.readFile(globalCssPath, 'utf8');
  const normalizedGlobalCss = globalCss
    .replace(/\/\* bleecker-generated-theme:start \*\/[\s\S]*?\/\* bleecker-generated-theme:end \*\//, '/* Design tokens are generated in tokens.generated.css. */')
    .replace(/\s*\/\* bleecker-generated-light:start \*\/[\s\S]*?\/\* bleecker-generated-light:end \*\//, '')
    .replace(/\s*\/\* bleecker-generated-dark:start \*\/[\s\S]*?\/\* bleecker-generated-dark:end \*\//, '');
  if (normalizedGlobalCss !== globalCss) {
    await fs.writeFile(globalCssPath, normalizedGlobalCss);
  }
  console.log(`[generate-token-css] Wrote ${path.relative(root, outputPath)}.`);
}
